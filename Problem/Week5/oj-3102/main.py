"""docstring module"""
def main():
    """main function"""
    year = int(input())
    cc = int(input())
    key_dict = {
        ("<1990","<1500") : 1250,
        ("<1990","1500-2000") : 1400,
        ("<1990",">2000") : 2000,

        ("1991-1999","<1500") : 1100,
        ("1991-1999","1500-2000") : 1300,
        ("1991-1999",">2000") : 1700,

        (">2000","<1500") : 1000,
        (">2000","1500-2000") : 1200,
        (">2000",">2000") : 1500,
    }
    if year <= 1990 :
        year = "<1990"
    elif 1990 < year < 2000:
        year = "1991-1999"
    else:
        year = ">2000"
    if cc <= 1500:
        cc = "<1500"
    elif 1500 < cc <= 2000:
        cc = "1500-2000"
    else:
        cc = ">2000"
    print(key_dict[(year,cc)])
main()
